CREATE FUNCTION public.bump_booking_availability(p_reason text DEFAULT 'booking')
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  UPDATE public.booking_availability_state
     SET version = version + 1,
         reason = left(coalesce(p_reason, 'booking'), 80),
         updated_at = now()
   WHERE id = 1;
END;
$$;

CREATE FUNCTION public.is_slot_open(p_slot_start timestamp with time zone)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_settings public.booking_settings%ROWTYPE;
  v_rule public.booking_availability_rules%ROWTYPE;
  v_local timestamp without time zone;
  v_local_date date;
  v_local_time time without time zone;
  v_dow integer;
  v_today date;
BEGIN
  SELECT * INTO v_settings FROM public.booking_settings WHERE id = 1;
  IF NOT FOUND OR p_slot_start IS NULL OR p_slot_start <= now() THEN
    RETURN false;
  END IF;
  v_local := p_slot_start AT TIME ZONE v_settings.timezone;
  v_local_date := v_local::date;
  v_local_time := v_local::time;
  v_dow := extract(dow from v_local_date)::integer;
  v_today := (now() AT TIME ZONE v_settings.timezone)::date;
  IF v_local_date < v_today OR v_local_date > (v_today + (v_settings.days_ahead - 1)) THEN
    RETURN false;
  END IF;
  SELECT * INTO v_rule FROM public.booking_availability_rules WHERE day_of_week = v_dow;
  IF NOT FOUND OR NOT v_rule.is_open THEN
    RETURN false;
  END IF;
  RETURN v_local_time >= v_rule.open_time
     AND (v_local_time + make_interval(mins => v_rule.slot_minutes)) <= v_rule.close_time;
END;
$$;

CREATE FUNCTION public.regenerate_booking_slots()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_settings public.booking_settings%ROWTYPE;
  v_rule public.booking_availability_rules%ROWTYPE;
  v_today date;
  v_date date;
  v_dow integer;
  v_local_slot timestamp without time zone;
  v_local_end timestamp without time zone;
  v_slot timestamptz;
  v_end timestamptz;
  v_step interval;
  v_count integer := 0;
  i integer;
BEGIN
  SELECT * INTO v_settings FROM public.booking_settings WHERE id = 1;
  v_today := (now() AT TIME ZONE v_settings.timezone)::date;

  -- Keep reserved slots. Only free slots are rebuilt when rules change.
  DELETE FROM public.booking_slots WHERE is_available = true;

  FOR i IN 0..(v_settings.days_ahead - 1) LOOP
    v_date := v_today + i;
    v_dow := extract(dow from v_date)::integer;
    SELECT * INTO v_rule FROM public.booking_availability_rules WHERE day_of_week = v_dow;
    IF FOUND AND v_rule.is_open THEN
      v_step := make_interval(mins => v_rule.slot_minutes);
      v_local_slot := v_date + v_rule.open_time;
      WHILE (v_local_slot + v_step) <= (v_date + v_rule.close_time) LOOP
        v_local_end := v_local_slot + v_step;
        v_slot := v_local_slot AT TIME ZONE v_settings.timezone;
        v_end := v_local_end AT TIME ZONE v_settings.timezone;
        IF v_slot > now() THEN
          INSERT INTO public.booking_slots (slot_start, slot_end, is_available, updated_at)
          VALUES (v_slot, v_end, true, now())
          ON CONFLICT (slot_start) DO NOTHING;
          v_count := v_count + 1;
        END IF;
        v_local_slot := v_local_end;
      END LOOP;
    END IF;
  END LOOP;
  PERFORM public.bump_booking_availability('availability-rules');
  RETURN v_count;
END;
$$;

CREATE FUNCTION public.expire_pending_bookings()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_count integer;
BEGIN
  UPDATE public.bookings
     SET status = 'expired', updated_at = now()
   WHERE status = 'pending'
     AND expires_at IS NOT NULL
     AND expires_at <= now();
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

CREATE FUNCTION public.ensure_booking_slots_current()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_settings public.booking_settings%ROWTYPE;
  v_today date;
BEGIN
  PERFORM public.expire_pending_bookings();
  SELECT * INTO v_settings FROM public.booking_settings WHERE id = 1;
  IF NOT FOUND THEN
    RETURN;
  END IF;
  v_today := (now() AT TIME ZONE v_settings.timezone)::date;
  IF v_settings.last_generated_date IS DISTINCT FROM v_today THEN
    PERFORM public.regenerate_booking_slots();
    UPDATE public.booking_settings
       SET last_generated_date = v_today,
           updated_at = now()
     WHERE id = 1;
  END IF;
END;
$$;

CREATE FUNCTION public.create_booking(
    p_patient_name text,
    p_patient_email text,
    p_patient_phone text,
    p_reason text,
    p_form_data jsonb,
    p_slot_start timestamp with time zone
)
RETURNS TABLE (
    booking_id integer,
    reserved_slot timestamp with time zone,
    booking_status text,
    hold_expires_at timestamp with time zone
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_settings public.booking_settings%ROWTYPE;
  v_slot public.booking_slots%ROWTYPE;
  v_booking public.bookings%ROWTYPE;
BEGIN
  PERFORM public.ensure_booking_slots_current();
  SELECT * INTO v_settings FROM public.booking_settings WHERE id = 1;
  IF p_slot_start IS NULL OR p_slot_start <= now() OR NOT public.is_slot_open(p_slot_start) THEN
    RAISE EXCEPTION 'SLOT_UNAVAILABLE' USING ERRCODE = 'P0001';
  END IF;

  -- Row lock + partial unique index make simultaneous submissions atomic.
  SELECT * INTO v_slot
    FROM public.booking_slots
   WHERE slot_start = p_slot_start
     AND is_available = true
     AND slot_start > now()
   FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'SLOT_UNAVAILABLE' USING ERRCODE = 'P0001';
  END IF;

  BEGIN
    INSERT INTO public.bookings (
      patient_name, patient_email, patient_phone, appointment_date, appointment_time,
      slot_start, expires_at, reason, status, form_data, created_at, updated_at
    ) VALUES (
      p_patient_name, p_patient_email, p_patient_phone,
      (p_slot_start AT TIME ZONE v_settings.timezone)::date::timestamp without time zone,
      to_char(p_slot_start AT TIME ZONE v_settings.timezone, 'HH24:MI'),
      p_slot_start,
      now() + make_interval(mins => v_settings.pending_hold_minutes),
      p_reason, 'pending', coalesce(p_form_data, '{}'::jsonb), now(), now()
    ) RETURNING * INTO v_booking;
  EXCEPTION WHEN unique_violation THEN
    RAISE EXCEPTION 'SLOT_UNAVAILABLE' USING ERRCODE = 'P0001';
  END;

  INSERT INTO public.notifications (type, title, message, is_read, related_type, related_id, created_at)
  VALUES ('booking', 'New booking request', 'A new appointment request is waiting for review.', false, 'booking', v_booking.id, now());

  RETURN QUERY SELECT v_booking.id, v_booking.slot_start, v_booking.status, v_booking.expires_at;
END;
$$;

CREATE FUNCTION public.booking_slot_sync()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_active text[] := array['pending','confirmed','completed'];
  v_old_active boolean;
  v_new_active boolean;
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.slot_start IS NOT NULL THEN
      IF NEW.status = ANY(v_active) THEN
        UPDATE public.booking_slots
           SET is_available = false, booking_id = NEW.id, updated_at = now()
         WHERE slot_start = NEW.slot_start;
      END IF;
      PERFORM public.bump_booking_availability('booking-created');
    END IF;
    RETURN NEW;
  ELSIF TG_OP = 'UPDATE' THEN
    v_old_active := OLD.status = ANY(v_active);
    v_new_active := NEW.status = ANY(v_active);
    IF OLD.slot_start IS NOT NULL
       AND (OLD.slot_start IS DISTINCT FROM NEW.slot_start OR (v_old_active AND NOT v_new_active)) THEN
      UPDATE public.booking_slots
         SET is_available = public.is_slot_open(OLD.slot_start),
             booking_id = NULL,
             updated_at = now()
       WHERE slot_start = OLD.slot_start AND booking_id = NEW.id;
    END IF;
    IF NEW.slot_start IS NOT NULL AND v_new_active
       AND (OLD.slot_start IS DISTINCT FROM NEW.slot_start OR (NOT v_old_active AND v_new_active)) THEN
      UPDATE public.booking_slots
         SET is_available = false, booking_id = NEW.id, updated_at = now()
       WHERE slot_start = NEW.slot_start;
    END IF;
    IF OLD.status IS DISTINCT FROM NEW.status OR OLD.slot_start IS DISTINCT FROM NEW.slot_start THEN
      PERFORM public.bump_booking_availability('booking-status');
    END IF;
    RETURN NEW;
  ELSIF TG_OP = 'DELETE' THEN
    IF OLD.slot_start IS NOT NULL THEN
      UPDATE public.booking_slots
         SET is_available = public.is_slot_open(OLD.slot_start),
             booking_id = NULL,
             updated_at = now()
       WHERE slot_start = OLD.slot_start AND booking_id = OLD.id;
      PERFORM public.bump_booking_availability('booking-deleted');
    END IF;
    RETURN OLD;
  END IF;
  RETURN NULL;
END;
$$;

CREATE FUNCTION public.notify_admin_event()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_id integer;
  v_payload jsonb;
BEGIN
  IF TG_OP = 'DELETE' THEN
    v_id := OLD.id;
  ELSE
    v_id := NEW.id;
  END IF;
  v_payload := jsonb_build_object(
    'table', TG_TABLE_NAME,
    'action', lower(TG_OP),
    'id', v_id
  );
  IF TG_TABLE_NAME = 'bookings' THEN
    v_payload := v_payload || jsonb_build_object(
      'status', CASE WHEN TG_OP = 'DELETE' THEN 'deleted' ELSE NEW.status END,
      'slot_start', CASE WHEN TG_OP = 'DELETE' THEN NULL ELSE NEW.slot_start END
    );
  ELSIF TG_TABLE_NAME = 'contact_messages' THEN
    v_payload := v_payload || jsonb_build_object(
      'is_read', CASE WHEN TG_OP = 'DELETE' THEN true ELSE NEW.is_read END
    );
  ELSIF TG_TABLE_NAME = 'notifications' THEN
    v_payload := v_payload || jsonb_build_object(
      'type', CASE WHEN TG_OP = 'DELETE' THEN 'deleted' ELSE NEW.type END,
      'is_read', CASE WHEN TG_OP = 'DELETE' THEN true ELSE NEW.is_read END
    );
  ELSIF TG_TABLE_NAME = 'messages' THEN
    v_payload := v_payload || jsonb_build_object(
      'status', CASE WHEN TG_OP = 'DELETE' THEN 'deleted' ELSE NEW.status END
    );
  END IF;
  -- Only ids/status flags travel on the admin event bus. No names, emails,
  -- phone numbers, reasons, message bodies or notification text are included.
  PERFORM pg_notify('fenote_admin_events', v_payload::text);
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

