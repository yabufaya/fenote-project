-- ── Production booking availability (PII-free public state only) ─────────
-- One appointment slot per configured interval. The public SPA never reads
-- bookings or contact_messages; it reads a version row and gets safe slot
-- choices from Express. Admin live events are delivered over authenticated SSE
-- from Postgres LISTEN/NOTIFY, not from a public Realtime publication.
CREATE TABLE public.booking_settings (
    id integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    timezone text NOT NULL DEFAULT 'Africa/Addis_Ababa',
    -- Public booking is a rolling one-week window from the clinic-local date.
    days_ahead integer NOT NULL DEFAULT 7 CHECK (days_ahead BETWEEN 1 AND 7),
    pending_hold_minutes integer NOT NULL DEFAULT 30 CHECK (pending_hold_minutes BETWEEN 5 AND 1440),
    last_generated_date date,
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE TABLE public.booking_availability_rules (
    day_of_week integer PRIMARY KEY CHECK (day_of_week BETWEEN 0 AND 6),
    is_open boolean NOT NULL DEFAULT false,
    open_time time without time zone NOT NULL DEFAULT '08:00'::time,
    close_time time without time zone NOT NULL DEFAULT '18:00'::time,
    slot_minutes integer NOT NULL DEFAULT 30 CHECK (slot_minutes BETWEEN 5 AND 240),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT booking_availability_open_window CHECK (NOT is_open OR close_time > open_time)
);

CREATE TABLE public.booking_slots (
    slot_start timestamp with time zone PRIMARY KEY,
    slot_end timestamp with time zone NOT NULL,
    is_available boolean NOT NULL DEFAULT true,
    booking_id integer REFERENCES public.bookings(id) ON DELETE SET NULL,
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT booking_slots_window CHECK (slot_end > slot_start)
);

CREATE TABLE public.booking_availability_state (
    id integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    version bigint NOT NULL DEFAULT 1,
    reason text NOT NULL DEFAULT 'initial',
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX bookings_active_slot_key
