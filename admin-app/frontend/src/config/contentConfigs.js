const text = (name, label, options = {}) => ({ name, label, type: 'text', ...options });
const area = (name, label, options = {}) => ({ name, label, type: 'textarea', rows: 4, ...options });
const number = (name, label, options = {}) => ({ name, label, type: 'number', ...options });
const select = (name, label, options, extra = {}) => ({ name, label, type: 'select', options, ...extra });
const file = (name, label, accept, extra = {}) => ({ name, label, type: 'file', accept, ...extra });
const url = (name, label, options = {}) => ({ name, label, type: 'text', inputMode: 'url', ...options });

